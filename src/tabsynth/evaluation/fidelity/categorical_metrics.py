"""Categorical marginal distribution fidelity metrics and unseen value auditing."""

from typing import Dict, List, Any, Optional, Set
import numpy as np
import pandas as pd


def compute_tvd(p_counts: pd.Series, q_counts: pd.Series) -> float:
    """Computes Total Variation Distance between two category frequency series.
    
    TVD(P, Q) = 0.5 * sum_{c in C} |P(c) - Q(c)| in [0, 1].
    """
    p_str = p_counts.copy()
    p_str.index = p_str.index.astype(str)
    q_str = q_counts.copy()
    q_str.index = q_str.index.astype(str)

    all_cats = sorted(list(set(p_str.index).union(set(q_str.index))))
    p_norm = p_str.reindex(all_cats, fill_value=0.0) / max(1.0, float(p_str.sum()))
    q_norm = q_str.reindex(all_cats, fill_value=0.0) / max(1.0, float(q_str.sum()))
    return float(0.5 * np.sum(np.abs(p_norm - q_norm)))


def compute_categorical_fidelity(
    real_df: pd.DataFrame,
    synth_df: pd.DataFrame,
    categorical_cols: List[str],
) -> Dict[str, Any]:
    """Computes categorical distribution fidelity metrics and tracks unseen categories.
    
    Evaluates:
        - Total Variation Distance per column and overall mean.
        - Per-category frequency deviations.
        - Missing-value frequency differences.
        - Unseen category rate (categories generated by synthesizer not present in real data).
        
    Args:
        real_df: Reference real DataFrame.
        synth_df: Evaluated synthetic DataFrame.
        categorical_cols: List of categorical column names.
        
    Returns:
        Dictionary containing aggregate summary metrics and per-column breakdowns.
    """
    tv_distances: Dict[str, float] = {}
    frequency_errors: Dict[str, Dict[str, float]] = {}
    unseen_categories: Dict[str, List[str]] = {}
    missing_freq_diffs: Dict[str, float] = {}

    for col in categorical_cols:
        if col not in real_df.columns or col not in synth_df.columns:
            continue

        r_series = real_df[col].fillna("<missing>").astype(str)
        s_series = synth_df[col].fillna("<missing>").astype(str)

        r_counts = r_series.value_counts(normalize=True)
        s_counts = s_series.value_counts(normalize=True)

        # 1. Total Variation Distance
        tvd = compute_tvd(r_counts, s_counts)
        tv_distances[col] = tvd

        # 2. Missing-value frequency difference
        r_miss = float(r_counts.get("<missing>", 0.0))
        s_miss = float(s_counts.get("<missing>", 0.0))
        missing_freq_diffs[col] = float(abs(r_miss - s_miss))

        # 3. Unseen Category Detection
        r_unique_cats: Set[str] = set(r_counts.index)
        s_unique_cats: Set[str] = set(s_counts.index)
        unseen = sorted(list(s_unique_cats - r_unique_cats))
        unseen_categories[col] = unseen

        # 4. Frequency Deviations per Category
        all_cats = sorted(list(r_unique_cats.union(s_unique_cats)))
        col_freq_errs = {}
        for cat in all_cats:
            col_freq_errs[cat] = float(abs(r_counts.get(cat, 0.0) - s_counts.get(cat, 0.0)))
        frequency_errors[col] = col_freq_errs

    mean_tvd = float(np.mean(list(tv_distances.values()))) if tv_distances else 0.0
    total_unseen = sum(len(u) for u in unseen_categories.values())

    return {
        "mean_tvd": mean_tvd,
        "total_unseen_categories": total_unseen,
        "tv_distances": tv_distances,
        "missing_frequency_differences": missing_freq_diffs,
        "unseen_categories": unseen_categories,
        "frequency_errors": frequency_errors,
    }
